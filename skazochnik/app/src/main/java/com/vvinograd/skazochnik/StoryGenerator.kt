package com.vvinograd.skazochnik

import kotlin.random.Random

/** Герой сказки с нужными падежными формами. */
data class Hero(
    val emoji: String,
    val title: String,
    val nom: String, // кто: дракончик Уголёк
    val ins: String, // с кем: дракончиком Угольком
    val female: Boolean,
)

/** Место приключения: куда отправились и где находятся. */
data class Place(val to: String, val at: String)

val HEROES = listOf(
    Hero("🐉", "Дракон", "дракончик Уголёк", "дракончиком Угольком", false),
    Hero("🐱", "Кот", "кот Мурлыка", "котом Мурлыкой", false),
    Hero("🦄", "Единорог", "единорожка Звёздочка", "единорожкой Звёздочкой", true),
    Hero("🤖", "Робот", "робот Винтик", "роботом Винтиком", false),
    Hero("🦊", "Лиса", "лисичка Ириска", "лисичкой Ириской", true),
    Hero("🦖", "Динозавр", "динозаврик Бублик", "динозавриком Бубликом", false),
)

private val PLACES = listOf(
    Place("в Конфетный лес", "в Конфетном лесу"),
    Place("на Луну", "на Луне"),
    Place("в подводное царство", "в подводном царстве"),
    Place("в Облачный город", "в Облачном городе"),
    Place("на Остров Великанов", "на Острове Великанов"),
    Place("в страну Радуг", "в стране Радуг"),
)

class StoryGenerator(private val random: Random = Random.Default) {

    /**
     * @param name имя ребёнка
     * @param girl true — девочка, false — мальчик
     */
    fun generate(name: String, girl: Boolean, hero: Hero): String {
        val n = name.trim().ifEmpty { if (girl) "Маша" else "Миша" }
        // окончания глаголов для ребёнка и героя
        fun k(m: String, f: String) = if (girl) f else m
        fun h(m: String, f: String) = if (hero.female) f else m

        val heroNom = hero.nom
        val heroCap = heroNom.replaceFirstChar { it.uppercase() }
        val place = PLACES.random(random)

        val opening = listOf(
            "Жил${k("", "а")}-был${k("", "а")} на свете ${k("мальчик", "девочка")} по имени $n.",
            "Однажды вечером, когда за окном зажглись первые звёзды, $n никак не мог${k("", "ла")} уснуть.",
            "В одном уютном доме, где пахло пирогами и какао, жил${k("", "а")} $n.",
        ).random(random)

        val friend = listOf(
            "А лучшим другом у ${k("него", "неё")} ${h("был", "была")} $heroNom.",
            "И был${h("", "а")} у ${k("него", "неё")} верный друг — $heroNom.",
        ).random(random)

        val call = "Вдруг $heroNom прибежал${h("", "а")} и прошептал${h("", "а")}: " +
            "«$n, скорее! Нам нужна твоя помощь ${place.at}!»"

        val travel = listOf(
            "Они сели на волшебный ковёр-самолёт и полетели ${place.to}.",
            "Они прыгнули в огромный мыльный пузырь, и ветер понёс их ${place.to}.",
            "Они открыли старую дверцу в шкафу, а за ней оказалась тропинка ${place.to}.",
            "Они надули воздушный шар, загадали желание — и через минуту очутились ${place.at}.",
        ).random(random)

        val adventure = listOf(
            "Там случилась беда: злой ветер Сквозняк унёс все улыбки, и жители ходили хмурые. " +
                "Тогда $n придумал${k("", "а")} смешную песенку, а $heroNom так забавно " +
                "затанцевал${h("", "а")}, что ветер расхохотался и вернул все улыбки обратно.",
            "Там пропал весь свет: маленький фонарщик потерял свой волшебный фонарик. " +
                "$n и $heroNom обыскали каждый уголок и нашли фонарик под большим лопухом. " +
                "Как только фонарщик его зажёг, всё вокруг засияло.",
            "Там жил великан, который храпел так громко, что никто не мог уснуть. " +
                "$n спел${k("", "а")} ему тихую колыбельную, а $heroNom укрыл${h("", "а")} " +
                "великана одеялом из облаков. Великан улыбнулся во сне и захрапел тихо-тихо, как котёнок.",
            "Там маленький котёнок забрался на высокую башню и боялся спуститься. " +
                "$n не растерял${k("ся", "ась")}: вместе с ${hero.ins} они построили лестницу " +
                "из радуги, и котёнок спустился прямо к ним в руки.",
            "Там кто-то перепутал все краски: трава стала синей, а небо — зелёным. " +
                "$n достал${k("", "а")} волшебную кисточку и вместе с ${hero.ins} " +
                "раскрасил${k("", "а")} всё обратно. Мир снова стал ярким и красивым.",
            "Там у королевы пропал торт ко дню рождения, а гости уже собирались. " +
                "$n и $heroNom испекли новый торт — из облаков, ягод и капельки волшебства. " +
                "Он получился самым вкусным на свете!",
        ).random(random)

        val celebration = "Все жители устроили праздник в их честь, с музыкой и фейерверком. " +
            "А потом $n и $heroNom вернулись домой — как раз к ужину."

        val moral = listOf(
            "Ведь самое главное волшебство — это дружба.",
            "Ведь когда друзья вместе, им ничего не страшно.",
            "Ведь даже маленькая доброта может изменить целый мир.",
            "Ведь смелость — это когда страшно, но ты всё равно помогаешь.",
        ).random(random)

        val ending = listOf(
            "Вечером $n ${k("лёг", "легла")} в кровать, закрыл${k("", "а")} глаза и улыбнул${k("ся", "ась")}. " +
                "Сказке конец, а кто слушал — молодец!",
            "$heroCap пожелал${h("", "а")} ${k("другу", "подружке")} спокойной ночи, и $n сладко уснул${k("", "а")}. " +
                "Спокойной ночи, $n!",
        ).random(random)

        return listOf(opening, friend, call, travel, adventure, celebration, moral, ending)
            .joinToString("\n\n")
    }
}
